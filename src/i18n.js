// default). Arabic switches the document to right-to-left.
//
// RULES (enforced by test/frontend.test.mjs):
//   • every key MUST have `en`; bn/ar fall back to en when absent, so a
//     missing translation can never break a page render
//   • views use translation keys (t('key')) — never hardcoded UI strings
//   • translate() never returns the raw key while an English entry exists

